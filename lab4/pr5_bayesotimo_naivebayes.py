"""## 9. Teste de significância entre os coeficientes Kappa
Esse é o item E do enunciado.

Precisamos comparar os resultados dos dois classificadores e avaliar se existe diferença estatisticamente significativa entre seus coeficientes Kappa.

A aula PR51 apresenta o teste:

$$Z_k = \frac{K_1 - K_2}{\sqrt{\sigma_1^2 + \sigma_2^2}}$$

Em que:
- $K_1$: Kappa do classificador de Bayes;
- $K_2$: Kappa do Naive Bayes;
- $\sigma_1^2$: variância do Kappa de Bayes;
- $\sigma_2^2$: variância do Kappa de Naive Bayes.

A hipótese nula é:

$$H_0: K_1 = K_2$$

A hipótese alternativa é:

$$H_1: K_1 \neq K_2$$
"""

# ============================================================
# TESTE DE SIGNIFICÂNCIA ENTRE OS KAPPAS
# ============================================================

def comparar_kappas(
    resultado_1,
    resultado_2
):

    kappa_1 = resultado_1["resumo"]["Kappa"]

    kappa_2 = resultado_2["resumo"]["Kappa"]

    variancia_1 = resultado_1["resumo"]["Variância do Kappa"]

    variancia_2 = resultado_2["resumo"]["Variância do Kappa"]

    denominador = np.sqrt(
        variancia_1 + variancia_2
    )

    if denominador == 0:

        z = np.nan
        p_valor = np.nan

    else:

        z = (kappa_1 - kappa_2) / denominador

        # p-valor bilateral da distribuição normal padrão
        p_valor = math.erfc(
            abs(z) / np.sqrt(2)
        )

    return {
        "Kappa Bayes": kappa_1,
        "Kappa Naive Bayes": kappa_2,
        "Z calculado": z,
        "p-valor": p_valor
    }


# ============================================================
