"""## 6. Naive Bayes Gaussiano

Também utiliza uma distribuição normal, mas supõe que os quatro atributos são condicionalmente independentes dentro de cada classe.

Assim, em vez de estimar uma matriz de covariância completa, calcula a média e a variância de cada atributo separadamente:

$$P(x \mid C_j) = \prod_{k=1}^{4} P(x_k \mid C_j)$$
"""

# ============================================================
# NAIVE BAYES GAUSSIANO
# ============================================================

def treinar_naive_bayes_gaussiano(X_treino, y_treino):

    classes = np.unique(y_treino)

    parametros = {}

    for classe in classes:

        # Seleciona os dados da classe
        X_classe = X_treino[y_treino == classe]

        # Média de cada atributo
        media = np.mean(X_classe, axis=0)

        # calcula a variância populacional independente para cada atributo
        variancias = np.var(
            X_classe,
            axis=0,# Calculo da variância por coluna
            ddof=0 # População
        )

        # Evita divisão por zero
        variancias = np.maximum(
            variancias,
            1e-9
        )

        # Guarda somente a média e as variancias
        parametros[classe] = {
            "media": media,
            "variancias": variancias
        }

    return parametros


# ============================================================
# FUNÇÃO DISCRIMINANTE DO NAIVE BAYES
# ============================================================

def pontuar_naive_bayes_gaussiano(
    X_amostras,
    parametros
):

    # Garante que as amostras sejam uma matriz
    X_amostras = np.atleast_2d(
        np.asarray(X_amostras, dtype=float)
    )

    diferencas = X_amostras - parametros["media"]

    # Log da multiplicação das densidades gaussianas
    pontuacao = -0.5 * np.sum(
        np.log(parametros["variancias"]) +
        (diferencas ** 2) / parametros["variancias"],
        axis=1
    )

    return pontuacao


