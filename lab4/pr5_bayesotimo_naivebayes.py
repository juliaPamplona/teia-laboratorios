"""## 5. Classificador de Bayes Gaussiano (covariância completa)

Considera os quatro atributos da flor em conjunto. Para cada classe, estima:
- Vetor de médias ($\\mu_j$);
- Matriz de covariância ($\\Sigma_j$)
- Densidade normal multivariada ($P(x \mid C_j)$).

A função discriminante que utilizaremos, omitindo os termos comuns às classes e as probabilidades a priori iguais, será:

$$g_j(x) = -\frac{1}{2}\ln|\Sigma_j| -\frac{1}{2}(x-\mu_j)^T\Sigma_j^{-1}(x-\mu_j)$$

A classe escolhida será aquela que apresentar o maior valor de $g_j(x)$.
"""

# ============================================================
# CLASSIFICADOR DE BAYES GAUSSIANO
# COVARIÂNCIA COMPLETA
# ============================================================

def treinar_bayes_gaussiano(X_treino, y_treino):

    classes = np.unique(y_treino)

    parametros = {}

    for classe in classes:

        # Seleciona os dados da classe
        X_classe = X_treino[y_treino == classe]

        # Vetor de médias
        media = np.mean(X_classe, axis=0)

        # Matriz de covariância
        diferencas = X_classe - media


        # ".T" ou "np.transpose", torna uma matriz transposta e "@" faz a multiplicação matricial
        covariancia = (
            diferencas.T @ diferencas
        ) / len(X_classe)

        # Sinal (positivo ou negativo), Determinante e logaritmo do determinante
        sinal, logdet = np.linalg.slogdet(covariancia)

        # Correção somente se a matriz não for positiva definida, adicionando um pequeno valor de sigma´ = sigma + 10**-8*I
        if sinal <= 0:
            covariancia = covariancia + (
                1e-8 * np.eye(X_treino.shape[1])
            )

            sinal, logdet = np.linalg.slogdet(covariancia)

        if sinal <= 0:
            raise ValueError(
                f"Matriz de covariância inválida para a classe {classe}"
            )

        # Guarda os parâmetros
        parametros[classe] = {
            "media": media,
            "covariancia": covariancia,
            "logdet": logdet
        }

    return parametros


# ============================================================
# FUNÇÃO DISCRIMINANTE GAUSSIANA
# ============================================================

# Calcula a pontuação para a classificação
def pontuar_bayes_gaussiano(X_amostras, parametros):

    # Garante que as amostras sejam uma matriz
    X_amostras = np.atleast_2d(
        np.asarray(X_amostras, dtype=float)
    )

    diferencas = X_amostras - parametros["media"]

    # Calcula a distância de Mahalanobis ao quadrado Sigma**-1(x - média)
    resolvido = np.linalg.solve(
        parametros["covariancia"],
        diferencas.T
    ).T

    # Calcula (x - média) * Sigma**-1(x - média)
    mahalanobis = np.sum(
        diferencas * resolvido,
        axis=1
    )

    # Função discriminante completa
    return -0.5 * (
        parametros["logdet"] + mahalanobis
    )


# ============================================================
# CLASSIFICAÇÃO
# ============================================================

def prever_modelo(
    X_amostras,
    parametros,
    funcao_pontuacao,
    classes=None
):

    if classes is None:
        classes = list(parametros.keys())

    pontuacoes = np.vstack([
        funcao_pontuacao(X_amostras, parametros[classe])
        for classe in classes
    ])

    indices = np.argmax(pontuacoes, axis=0)

    return np.asarray(classes)[indices]


