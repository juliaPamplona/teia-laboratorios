"""6. Matriz de confusão e métricas de qualidade

O próximo passo é avaliar os dois classificadores. Avaliamos observando a matriz de confusão, acurácia global, acurácia do produtor, acurácia do usuário, Kappa e demais medidas de qualidade.

É importante lembar que utilizamos a convenção da matriz da aula: linhas representam as classes preditas e colunas representam as classes reais.
"""

import math

# ============================================================
# MATRIZ DE CONFUSÃO
# Linhas = predição
# Colunas = classe real
# ============================================================

def calcular_matriz_confusao(
    y_real,
    y_predito,
    classes
):

    # Cria uma matriz vazia
    matriz = np.zeros(
        (len(classes), len(classes)),
        dtype=int
    )

    # Cria o mapa de classes para transformar o número da classe em uma posição da matriz
    mapa = {
        classe: i
        for i, classe in enumerate(classes)
    }

    for real, predito in zip(y_real, y_predito):

        i = mapa[predito]
        j = mapa[real]

        matriz[i, j] += 1

    return matriz


# ============================================================
# VARIÂNCIA DO KAPPA - CONFORME A AULA PR51
# ============================================================

def calcular_variancia_kappa(matriz):

    # Soma todos os elementos da matriz
    n = matriz.sum()

    linhas = matriz.sum(axis=1)
    colunas = matriz.sum(axis=0)

    # Acurácia golbal somando o total de acertos e dividindo pelo total de amostras
    acerto_global = np.trace(matriz) / n

    # Acurácia casual com o somatório das linhas vezes coluna dividido pelo total ao quadrado
    acerto_casual = np.sum(
        linhas * colunas
    ) / (n ** 2)

    theta1 = acerto_global
    theta2 = acerto_casual

    theta3 = np.sum(
        np.diag(matriz) * (linhas + colunas)
    ) / (n ** 2)

    theta4 = 0

    for i in range(len(matriz)):
        for j in range(len(matriz)):

            theta4 += (
                matriz[i, j] *
                (linhas[j] + colunas[i]) ** 2
            )

    theta4 = theta4 / (n ** 3)

    if abs(1 - theta2) < 1e-12:
        return np.nan

    variancia = (1 / n) * (
        theta1 * (1 - theta1) / (1 - theta2) ** 2

        + 2 * (1 - theta1) *
        (2 * theta1 * theta2 - theta3) /
        (1 - theta2) ** 3

        + (1 - theta1) ** 2 *
        (theta4 - 4 * theta2 ** 2) /
        (1 - theta2) ** 4
    )

    return max(0, variancia)


# ============================================================
# MÉTRICAS DE QUALIDADE
# ============================================================

def calcular_metricas(
    y_real,
    y_predito,
    classes
):

    matriz = calcular_matriz_confusao(
        y_real,
        y_predito,
        classes
    )

    n = matriz.sum()

    linhas = matriz.sum(axis=1)
    colunas = matriz.sum(axis=0)

    acuracia_global = np.trace(matriz) / n

    # Acerto casual
    acerto_casual = np.sum(
        linhas * colunas
    ) / (n ** 2)

    # Kappa
    if abs(1 - acerto_casual) > 1e-12:
        kappa = (
            acuracia_global - acerto_casual
        ) / (1 - acerto_casual)
    else:
        kappa = np.nan

    # Variância do Kappa
    variancia_kappa = calcular_variancia_kappa(matriz)

    # Significância do Kappa em relação ao acaso
    if variancia_kappa > 0:

      z_kappa = kappa / np.sqrt(variancia_kappa)

      p_kappa = math.erfc(
          abs(z_kappa) / np.sqrt(2)
      )

    elif np.isclose(variancia_kappa, 0):

      if kappa > 0:
        z_kappa = np.inf
        p_kappa = 0.0

      elif np.isclose(kappa, 0):
        z_kappa = 0.0
        p_kappa = 1.0

      else:
        z_kappa = -np.inf
        p_kappa = 0.0

    else:
      z_kappa = np.nan
      p_kappa = np.nan

    # Coeficiente Tau: chance uniforme entre as classes
    quantidade_classes = len(classes)

    tau = (
        (acuracia_global - 1 / quantidade_classes) /
        (1 - 1 / quantidade_classes)
    )

    # MCC multiclasse
    numerador_mcc = (
        n * np.trace(matriz) -
        np.sum(linhas * colunas)
    )

    denominador_mcc = np.sqrt(
        (n ** 2 - np.sum(linhas ** 2)) *
        (n ** 2 - np.sum(colunas ** 2))
    )

    if denominador_mcc > 0:
        mcc_global = numerador_mcc / denominador_mcc
    else:
        mcc_global = 0

    # Métricas individuais por classe
    resultados_classes = []

    for i, classe in enumerate(classes):

        # Diagonal
        vp = matriz[i, i]

        # Total da linha menos os verdadeiros positivos
        fp = linhas[i] - vp

        # Total da coluna menos os verdadeiros positivos
        fn = colunas[i] - vp

        # Tudo que não pertence aos 3 casos anteriores
        vn = n - vp - fp - fn

        precisao = (
            vp / (vp + fp)
            if (vp + fp) > 0 else 0
        )

        sensibilidade = (
            vp / (vp + fn)
            if (vp + fn) > 0 else 0
        )

        especificidade = (
            vn / (vn + fp)
            if (vn + fp) > 0 else 0
        )

        f1 = (
            2 * precisao * sensibilidade /
            (precisao + sensibilidade)
            if (precisao + sensibilidade) > 0 else 0
        )

        f2 = (
            5 * precisao * sensibilidade /
            (4 * precisao + sensibilidade)
            if (4 * precisao + sensibilidade) > 0 else 0
        )

        denominador = np.sqrt(
            (vp + fp) *
            (vp + fn) *
            (vn + fp) *
            (vn + fn)
        )

        if denominador > 0:
            mcc_classe = (
                vp * vn - fp * fn
            ) / denominador
        else:
            mcc_classe = 0

        resultados_classes.append({
            "Classe": nomes_classes[classe],
            "Precisão / Acurácia do usuário": precisao,
            "Sensibilidade / Acurácia do produtor": sensibilidade,
            "Especificidade": especificidade,
            "F1-score": f1,
            "F2-score": f2,
            "MCC (OvR)": mcc_classe
        })

    tabela_metricas = pd.DataFrame(
        resultados_classes
    ).set_index("Classe")

    colunas_metricas = tabela_metricas.columns

    # Média macro
    media_macro = tabela_metricas.mean(axis=0)

    # Média ponderada pela quantidade real de amostras
    media_ponderada = {}

    for coluna in colunas_metricas:

        valores = tabela_metricas[coluna].to_numpy()

        media_ponderada[coluna] = np.average(
            valores,
            weights=colunas
        )

    tabela_metricas.loc["Média macro"] = media_macro

    tabela_metricas.loc["Média ponderada"] = media_ponderada

    resumo = {
        "Acurácia global": acuracia_global,
        "Acurácia casual": acerto_casual,
        "Kappa": kappa,
        "Variância do Kappa": variancia_kappa,
        "Z do Kappa": z_kappa,
        "p-valor do Kappa": p_kappa,
        "Tau": tau,
        "MCC multiclasse": mcc_global
    }

    return matriz, tabela_metricas, resumo

